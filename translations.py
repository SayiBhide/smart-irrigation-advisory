def tr(language, key, **kwargs):
    value = T[language].get(key, T["English"].get(key, key))
    if isinstance(value, str) and kwargs:
        return value.format(**kwargs)
    return value

def display_crop(language, value):
    return T[language]["crops"].get(value, value)

def display_stage(language, value):
    return T[language]["stages"].get(value, value)

def display_weather_condition(language, weather_main, fallback):
    return T[language]["weather_conditions"].get(weather_main, fallback)

def localized_advisory(language, prediction, rainfall_forecast, rain_probability):
    key = {"low": "low_advice", "medium": "medium_advice", "high": "high_advice"}.get(prediction.lower(), "unknown_advice")
    message = T[language][key]
    if rainfall_forecast >= 5 or rain_probability >= 60:
        message += " " + T[language]["rain_warning"]
    return message
